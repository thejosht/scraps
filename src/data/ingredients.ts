export const ingredientGroups = ingredients.filter(
  (ingredient): ingredient is IngredientGroup =>
    ingredient.specificity === "group",
);

export const ingredientSubgroups = ingredients.filter(
  (ingredient): ingredient is IngredientSubgroup =>
    ingredient.specificity === "subgroup",
);

export const specificIngredients = ingredients.filter(
  (ingredient): ingredient is SpecificIngredient =>
    ingredient.specificity === "specific",
);

export const ingredientsById = new Map(
  ingredients.map((ingredient) => [ingredient.id, ingredient]),
);

export function getIngredientById(id: IngredientId) {
  return ingredientsById.get(id);
}

export function getIngredientsByParentId(parentId?: IngredientId) {
  if (!parentId) {
    return ingredientGroups;
  }

  return ingredients.filter(
    (ingredient): ingredient is IngredientTreeNode =>
      ingredient.parentId === parentId,
  );
}

export function searchIngredients(query: string) {
  const normalizedQuery = query.trim().toLowerCase();

  if (!normalizedQuery) {
    return specificIngredients;
  }

  return ingredients.filter((ingredient) => {
    const searchableValues = [
      ingredient.name,
      ingredient.category,
      ingredient.subcategory ?? "",
      ...ingredient.synonyms,
    ].map((value) => value.toLowerCase());

    return searchableValues.some((value) => value.includes(normalizedQuery));
  });
}
