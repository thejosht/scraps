import type {
  Ingredient,
  IngredientGroup,
  IngredientId,
  IngredientSubgroup,
  IngredientTreeNode,
  SpecificIngredient,
} from "@/types";

type IngredientInput = Omit<
  Ingredient,
  | "aliases"
  | "commonPairings"
  | "dietaryTags"
  | "isCommon"
  | "isPantryBasic"
  | "kind"
  | "label"
  | "storage"
  | "synonyms"
  | "tags"
  | "unlocksTemplates"
> &
  Partial<
    Pick<
      Ingredient,
      | "aliases"
      | "commonPairings"
      | "dietaryTags"
      | "isCommon"
      | "isPantryBasic"
      | "storage"
      | "synonyms"
      | "tags"
      | "unlocksTemplates"
    >
  >;

function defineIngredient(input: IngredientInput): Ingredient {
  const synonyms = input.synonyms ?? [];

  return {
    ...input,
    label: input.name,
    kind: input.specificity,
    synonyms,
    aliases: input.aliases ?? synonyms,
    commonPairings: input.commonPairings ?? [],
    unlocksTemplates: input.unlocksTemplates ?? [],
    dietaryTags: input.dietaryTags ?? [],
    storage: input.storage ?? input.storageType,
    isPantryBasic: input.isPantryBasic ?? input.storageType === "pantry",
    isCommon: input.isCommon ?? true,
    tags: input.tags ?? [],
  };
}

const group = (
  id: IngredientId,
  name: string,
  tags: Ingredient["tags"] = [],
) =>
  defineIngredient({
    id,
    name,
    category: name,
    specificity: "group",
    isCommon: true,
    isPantryBasic: false,
    tags,
  }) as IngredientGroup;

const subgroup = (
  id: IngredientId,
  name: string,
  category: string,
  parentId: IngredientId,
  tags: Ingredient["tags"] = [],
) =>
  defineIngredient({
    id,
    name,
    category,
    subcategory: name,
    parentId,
    specificity: "subgroup",
    isCommon: true,
    isPantryBasic: false,
    tags,
  }) as IngredientSubgroup;

const specific = (
  input: Omit<IngredientInput, "specificity"> & {
    parentId: IngredientId;
    subcategory: string;
  },
) =>
  defineIngredient({
    ...input,
    specificity: "specific",
  }) as SpecificIngredient;

